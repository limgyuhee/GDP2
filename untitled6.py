import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.linear_model import LinearRegression
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score

file_path = "gdp_pcap.csv"
df = pd.read_csv(file_path)

display(df.head())

print("Dataset shape (rows, columns):", df.shape)
print("\nFirst 10 column names:")
print(df.columns[:10].tolist())

print("\nDataset information:")
df.info()

print("\nSummary statistics for numeric columns:")
display(df.describe())

print("Total missing values:", int(df.isna().sum().sum()))
print("\nColumns with the most missing values:")
display(df.isna().sum().sort_values(ascending=False).head(15))

print("\nDuplicate rows:", df.duplicated().sum())
print("Duplicate country/region names:", df["name"].duplicated().sum())
display(df[["geo", "name"]].head(10))

year_cols_all = [col for col in df.columns if str(col).isdigit()]
year_cols_all = sorted(year_cols_all, key=lambda value: int(value))

start_year = 1800
end_year = 2023
year_cols = [col for col in year_cols_all if start_year <= int(col) <= end_year]

print("Selected year range:", year_cols[0], "to", year_cols[-1])
print("Number of selected year columns:", len(year_cols))

df_clean = df.copy()

for col in year_cols:
    df_clean[col] = pd.to_numeric(df_clean[col], errors="coerce")

print("Missing values in selected year columns:",
      int(df_clean[year_cols].isna().sum().sum()))

annual_mean = df_clean[year_cols].mean(axis=0, skipna=True)

time_series = pd.DataFrame({
    "Year": annual_mean.index.astype(int),
    "Mean_GDP_per_capita": annual_mean.values
}).sort_values("Year").reset_index(drop=True)

time_series = time_series.dropna(subset=["Mean_GDP_per_capita"])

display(time_series.head())
display(time_series.tail())
print("Number of yearly observations:", len(time_series))
print("Year range:", time_series["Year"].min(), "to", time_series["Year"].max())
print("\nMissing values in processed data:")
print(time_series.isna().sum())

plt.figure(figsize=(12, 5))
plt.plot(time_series["Year"], time_series["Mean_GDP_per_capita"])
plt.title("Average GDP per Capita Across Countries (1800–2023)")
plt.xlabel("Year")
plt.ylabel("Mean GDP per capita (dataset units)")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

window_size = min(30, len(time_series))
recent_data = time_series.tail(window_size).reset_index(drop=True)

X_recent = recent_data[["Year"]]
y_recent = recent_data["Mean_GDP_per_capita"]

test_size = min(5, max(1, len(recent_data) // 5))
split_index = len(recent_data) - test_size

if split_index < 2:
    raise ValueError("There are not enough yearly observations for a chronological train-test split.")

X_train = X_recent.iloc[:split_index]
X_test = X_recent.iloc[split_index:]
y_train = y_recent.iloc[:split_index]
y_test = y_recent.iloc[split_index:]

print(f"Model window: {recent_data['Year'].min()}–{recent_data['Year'].max()}")
print(f"Training years: {X_train['Year'].min()}–{X_train['Year'].max()}")
print(f"Testing years: {X_test['Year'].min()}–{X_test['Year'].max()}")

evaluation_model = LinearRegression()
evaluation_model.fit(X_train, y_train)

test_predictions = evaluation_model.predict(X_test)

mae = mean_absolute_error(y_test, test_predictions)
rmse = np.sqrt(mean_squared_error(y_test, test_predictions))
r2 = r2_score(y_test, test_predictions)

print(f"MAE:  {mae:.4f}")
print(f"RMSE: {rmse:.4f}")
print(f"R²:   {r2:.4f}")

test_results = pd.DataFrame({
    "Year": X_test["Year"].values,
    "Actual": y_test.values,
    "Predicted": test_predictions
})
test_results["Error"] = test_results["Actual"] - test_results["Predicted"]

display(test_results)

plt.figure(figsize=(12, 5))
plt.plot(time_series["Year"], time_series["Mean_GDP_per_capita"],
         label="Historical mean", linewidth=2)
plt.plot(test_results["Year"], test_results["Predicted"],
         label="Test-period predictions", linestyle="--", marker="o")
plt.title("Linear Regression: Actual Values and Test Predictions")
plt.xlabel("Year")
plt.ylabel("Mean GDP per capita (dataset units)")
plt.legend()
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()